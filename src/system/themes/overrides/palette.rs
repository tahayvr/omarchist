pub fn find_bundle(id: &str) -> Option<&'static PaletteBundle> {
    BUNDLES.iter().find(|bundle| bundle.id == id)
}

/// The bundle a file is generated by, if any.
pub fn bundle_of(file: &str) -> Option<&'static PaletteBundle> {
    BUNDLES.iter().find(|bundle| bundle.files.contains(&file))
}

/// A `colors.toml` key a bundle can change, labelled as on the Colors tab.
#[derive(Debug)]
pub struct BaseKey {
    pub key: &'static str,
    pub label: &'static str,
    pub group: &'static str,
}

const fn base(key: &'static str, label: &'static str, group: &'static str) -> BaseKey {
    BaseKey { key, label, group }
}

