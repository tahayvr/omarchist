//! Override files generated from the theme's palette with some colors
//! changed. A bundle renders Omarchy's own templates for its files from the
//! theme's `colors.toml` with the user's changes applied, so one set of colors
//! drives several files (every terminal config at once) and the colors left
//! alone keep following the palette. The changes live in `omarchist.json`
//! (`EditingTheme::palettes`); the files are only ever generated.

