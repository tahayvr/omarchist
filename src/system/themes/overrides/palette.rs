/// Files generated together from one set of colors.
#[derive(Debug)]
pub struct PaletteBundle {
    /// Key in `EditingTheme::palettes`.
    pub id: &'static str,
    pub app: &'static str,
    pub description: &'static str,
    pub category: Category,
    pub files: &'static [&'static str],
    /// Programs that consume the files. Empty when always relevant.
    pub binaries: &'static [&'static str],
}

